// Credit-note PDF, laid out like the invoice PDF in pdfService.js
const { S3Client, PutObjectCommand } = require('@aws-sdk/client-s3');
const PDFDocument = require('pdfkit');
const path = require('path');

const s3 = new S3Client({
  region: process.env.AWS_REGION || 'us-west-1',
  credentials: {
    accessKeyId: process.env.AWS_ACCESS_KEY_ID || '',
    secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY || '',
  }
});

const formatCA = (date, withTime = false) => {
  if (!date) return '—';
  return new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/Los_Angeles',
    month: '2-digit',
    day: '2-digit',
    year: 'numeric',
    ...(withTime && { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: true })
  }).format(new Date(date));
};

const money = (n) => `$${(Number(n) || 0).toFixed(2)}`;

// creditNote: { credit_note_number, issued_at, amount }, orderReturn: { return_date, reason, items[] },
// order: { id }, shop: { shop_name, ... }, invoice: { final_amount, total_paid_amount, total_credited_amount }
const generateCreditNotePDFBuffer = ({ creditNote, orderReturn, order, shop, invoice }) => {
  return new Promise((resolve, reject) => {
    const PAGE_WIDTH = 612;
    const MARGIN_LEFT = 50;
    const CONTENT_WIDTH = 512;
    const FOOTER_Y = 720;
    const MAX_TABLE_Y = FOOTER_Y - 5;
    const SELLER_PERMIT = '251551552-00003';
    const SELLER_TOBACCO_LICENSE = '257743008';
    const BRAND = '#002d72';

    const doc = new PDFDocument({ margins: { top: 40, bottom: 30, left: 50, right: 50 }, size: 'LETTER', autoFirstPage: true });
    const buffers = [];
    doc.on('data', buffers.push.bind(buffers));
    doc.on('end', () => resolve(Buffer.concat(buffers)));
    doc.on('error', reject);

    const logoPath = path.join(__dirname, '../uploads/logo.png');

    const drawWatermark = () => {
      doc.save();
      doc.opacity(0.08);
      doc.image(logoPath, 106, 196, { width: 400 });
      doc.restore();
    };

    const drawFooter = () => {
      doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(MARGIN_LEFT, FOOTER_Y).lineTo(562, FOOTER_Y).stroke();
      doc.fillColor('#475569').fontSize(8).font('Helvetica-Bold')
        .text(`Seller Permit: ${SELLER_PERMIT}  |  Tobacco License: ${SELLER_TOBACCO_LICENSE}`, MARGIN_LEFT, FOOTER_Y + 8, { align: 'center', width: CONTENT_WIDTH });
      doc.fillColor('#94a3b8').fontSize(8).font('Helvetica')
        .text(`This credit note is issued against invoice INV-${order.id} and does not replace it.`, MARGIN_LEFT, FOOTER_Y + 20, { align: 'center', width: CONTENT_WIDTH });
      doc.fillColor('#cbd5e1')
        .text(`Generated by Woodland Distributors on ${formatCA(new Date(), true)}`, MARGIN_LEFT, FOOTER_Y + 32, { align: 'center', width: CONTENT_WIDTH });
    };

    const drawTableHeader = (y) => {
      doc.rect(MARGIN_LEFT, y, CONTENT_WIDTH, 22).fill(BRAND);
      doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold');
      doc.text('S.No.', 55, y + 7, { width: 30 });
      doc.text('Returned Product', 88, y + 7, { width: 180 });
      doc.text('SKU ID', 270, y + 7, { width: 70 });
      doc.text('Qty', 340, y + 7, { width: 40, align: 'right' });
      doc.text('Unit Price', 390, y + 7, { width: 80, align: 'right' });
      doc.text('Credit', 480, y + 7, { width: 72, align: 'right' });
      return y + 22;
    };

    const newPage = () => {
      doc.addPage();
      doc.rect(0, 0, PAGE_WIDTH, 10).fill(BRAND);
      drawWatermark();
      drawFooter();
    };

    // Header
    doc.rect(0, 0, PAGE_WIDTH, 10).fill(BRAND);
    doc.fillColor(BRAND).fontSize(22).font('Helvetica-Bold').text('Woodland Distributors', 50, 32);
    doc.fillColor('#1e293b').fontSize(22).font('Helvetica-Bold').text('CREDIT NOTE', 360, 35, { align: 'right', width: 202 });

    const metaY = 75;
    const meta = [
      ['Credit Note No:', creditNote.credit_note_number, true],
      ['Date:', formatCA(creditNote.issued_at)],
      ['Original Invoice:', `INV-${order.id}`],
      ['Order ID:', `WS-${order.id}`],
      ['Return Date:', formatCA(orderReturn.return_date)],
    ];
    meta.forEach(([label, value, bold], i) => {
      doc.fontSize(9).font('Helvetica').fillColor('#64748b').text(label, 380, metaY + i * 14, { width: 90, align: 'left' });
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fillColor('#1e293b').text(value, 470, metaY + i * 14, { width: 92, align: 'right' });
    });

    doc.font('Helvetica').fontSize(9).fillColor('#475569');
    doc.text('1233 E Beamer St Suite E1', 50, 90);
    doc.text('Woodland, CA 95776, United States', 50, 102);
    doc.text('Phone: +1 530-490-8786', 50, 114);

    doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(50, 155).lineTo(562, 155).stroke();

    // Credit To
    const billToY = 170;
    doc.fillColor(BRAND).fontSize(10).font('Helvetica-Bold').text('CREDIT TO', 50, billToY);
    doc.fillColor('#0f172a').fontSize(11).font('Helvetica-Bold').text(shop.shop_name, 50, billToY + 15);
    doc.font('Helvetica').fontSize(9).fillColor('#334155');
    doc.text(`Address: ${[shop.address, shop.city, shop.state, shop.zip].filter(Boolean).join(', ') || 'N/A'}`, 50, billToY + 30, { width: 350 });
    doc.text(`Seller Permit: ${shop.seller_permit || 'N/A'}`, 50, billToY + 44);
    if (shop.tobacco_license) doc.text(`Tobacco License: ${shop.tobacco_license}`, 50, billToY + 56);

    drawWatermark();
    drawFooter();

    // Returned items
    let position = drawTableHeader(260);
    const items = [...(orderReturn.items || [])].sort((a, b) =>
      (a.product_name || '').localeCompare(b.product_name || '', undefined, { sensitivity: 'base' }));

    items.forEach((item, index) => {
      const name = item.product_name || `Product #${item.product_id}`;
      doc.fontSize(9).font('Helvetica');
      const textHeight = doc.heightOfString(name, { width: 180 });
      const rowHeight = Math.max(22, textHeight + 10);
      if (position + rowHeight > MAX_TABLE_Y) {
        newPage();
        position = drawTableHeader(30);
        doc.fontSize(9).font('Helvetica');
      }
      const valOffset = position + (rowHeight - 9) / 2;
      doc.fillColor('#1e293b');
      doc.text(String(index + 1), 55, valOffset, { width: 30 });
      doc.text(name, 88, position + (rowHeight - textHeight) / 2, { width: 180 });

      const sku = item.sku_id || '—';
      const skuWidth = doc.widthOfString(sku);
      const skuFont = skuWidth > 70 ? Math.max(5.5, (9 * 70) / skuWidth) : 9;
      doc.fontSize(skuFont).text(sku, 270, position + (rowHeight - skuFont) / 2, { width: 70, lineBreak: false });
      doc.fontSize(9);
      doc.text(String(item.quantity), 340, valOffset, { width: 40, align: 'right' });
      doc.text(money(item.unit_price), 390, valOffset, { width: 80, align: 'right' });
      doc.text(money(item.line_total), 480, valOffset, { width: 72, align: 'right' });
      doc.strokeColor('#f1f5f9').lineWidth(0.5).moveTo(50, position + rowHeight).lineTo(562, position + rowHeight).stroke();
      position += rowHeight;
    });

    // Reason + totals (~120pt)
    if (position + 120 > MAX_TABLE_Y) {
      newPage();
      position = 30;
    }
    position += 15;
    if (orderReturn.reason) {
      doc.fillColor('#64748b').fontSize(9).font('Helvetica-Bold').text('Reason for return', 50, position);
      doc.fillColor('#334155').font('Helvetica').text(orderReturn.reason, 50, position + 13, { width: 270 });
    }

    doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(350, position).lineTo(562, position).stroke();
    let y = position + 10;
    const row = (label, value, opts = {}) => {
      doc.fillColor('#64748b').fontSize(9).font('Helvetica').text(label, 330, y, { width: 120, align: 'right' });
      doc.fillColor(opts.color || '#1e293b').font('Helvetica-Bold').text(value, 450, y, { width: 112, align: 'right' });
      y += 15;
    };
    row(`Original invoice INV-${order.id}:`, money(invoice.final_amount));
    row('Paid to date:', money(invoice.total_paid_amount));
    row('Total credited (incl. this note):', money(invoice.total_credited_amount));

    doc.strokeColor('#cbd5e1').lineWidth(0.5).moveTo(350, y).lineTo(562, y).stroke();
    y += 8;
    doc.fillColor('#475569').fontSize(10).font('Helvetica-Bold').text('Credit Amount:', 330, y, { width: 120, align: 'right' });
    doc.fillColor(BRAND).fontSize(14).font('Helvetica-Bold').text(money(creditNote.amount), 450, y - 3, { width: 112, align: 'right' });

    doc.end();
  });
};

const uploadCreditNotePDF = async (data) => {
  const buffer = await generateCreditNotePDFBuffer(data);
  const key = `credit-notes/${data.creditNote.credit_note_number}-${Date.now()}.pdf`;
  const bucket = process.env.AWS_S3_BUCKET || 'wdistro';
  await s3.send(new PutObjectCommand({
    Bucket: bucket,
    Key: key,
    Body: buffer,
    ContentType: 'application/pdf',
  }));
  return `https://${bucket}.s3.${process.env.AWS_REGION || 'us-west-1'}.amazonaws.com/${key}`;
};

module.exports = { generateCreditNotePDFBuffer, uploadCreditNotePDF };
